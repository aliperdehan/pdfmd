"""Non-clashing pdfmd options at the top level of each metadata layer.

The explicit block wins within its own layer. Original metadata stays intact for custom templates. The shipped key data
is generated by scripts/pandoc_keys.py: reading a document never starts Pandoc or inspects an installed Quarto schema.
"""

from __future__ import annotations

import json
from functools import cache
from pathlib import Path

from pdfmd_base import core


@cache
def key_data():
    return json.loads(Path(__file__).with_name("pandoc_keys.json").read_text(encoding="utf-8"))


@cache
def known_keys():
    from pdfmd_setup.inventory import OPTIONS

    return frozenset(key.split(".", 1)[0] for key in OPTIONS)


def from_mapping(data, source):
    if not isinstance(data, dict):
        return {}
    explicit = data.get("pdfmd-options")
    options = dict(explicit) if isinstance(explicit, dict) else {}
    keys = key_data()
    clashes = set(keys["template_keys"]) | set(keys["documented_keys"])
    if source.suffix.lower() in (".qmd", ".rmd"):
        if keys["quarto_keys"] is None:
            return options
        clashes.update(keys["quarto_keys"])
    for key in sorted(data.keys() & known_keys() - clashes - options.keys()):
        options[key] = data[key]
        if core.VERBOSE_OUTPUT:
            value = data[key] if isinstance(data[key], str) else json.dumps(data[key], ensure_ascii=False, default=str)
            message = f"OPTIONS  {key}: {value} (top level of {core.display_path(source)})"
            seen = core.BUILD.setdefault("top-level-option-notes", [])
            if message not in seen:
                seen.append(message)
                print(message)
    return options


def metadata_mapping(data, source):
    """Expose resolved options to all existing readers without consuming a custom template's metadata."""
    if not isinstance(data, dict):
        return {}
    options = from_mapping(data, source)
    return {**data, "pdfmd-options": options} if options else data


def legacy_engine(source, options):
    """Keep legacy engine metadata, without undoing this layer's explicit false/null precedence."""
    for key in ("pdf-engine", "engine"):
        if key in options:
            continue
        value = source.get(key) if isinstance(source, dict) else core.frontmatter_value(source, key)
        if value:
            return value
    return None
