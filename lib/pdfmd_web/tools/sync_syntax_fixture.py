#!/usr/bin/env python3
"""Copies syntax/syntaxes.json into fixtures/fixtures.js (the page opened from disk cannot fetch it), leaving the rest of the fixtures as they are.
`make_fixtures.py` does the same as part of a full run; run this one after editing the table: python3 tools/sync_syntax_fixture.py"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
HEAD = "// generated by tools/make_fixtures.py: do not edit\nwindow.FIXTURES = "
path = HERE / "fixtures" / "fixtures.js"
text = path.read_text()
assert text.startswith(HEAD) and text.endswith(";\n"), "fixtures.js is not in the shape make_fixtures.py writes"
fixtures = json.loads(text[len(HEAD):-2])
fixtures["syntaxes"] = json.loads((HERE / "syntax" / "syntaxes.json").read_text())
path.write_text(HEAD + json.dumps(fixtures, ensure_ascii=False, indent=1) + ";\n")
print("fixtures.js now carries the syntax table")
