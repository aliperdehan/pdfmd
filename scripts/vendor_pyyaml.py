#!/usr/bin/env python3
"""Regenerate lib/pdfmd_yaml/ from this Python's installed PyYAML (no network).

    python3 scripts/vendor_pyyaml.py                 # installed PyYAML 6.0.3
    python3 scripts/vendor_pyyaml.py --version X.Y.Z # deliberately update
    python3 scripts/vendor_pyyaml.py --check         # report drift, change nothing

The private copy is generated, never hand-edited. Only pure-Python modules
are copied, with PyYAML's MIT licence from its distribution metadata.
"""
from __future__ import annotations

import argparse
import hashlib
from importlib.metadata import distribution
from pathlib import Path
import re
import shutil
import sys

PYYAML_VERSION = '6.0.3'
TARGET = Path(__file__).resolve().parent.parent / 'lib' / 'pdfmd_yaml'


def build(version: str) -> dict[str, bytes]:
    dist = distribution('pyyaml')
    if dist.version != version:
        raise SystemExit(f'Installed PyYAML is {dist.version}; requested {version}')
    files = {}
    hashes = []
    for entry in sorted(dist.files or []):
        name = entry.as_posix()
        if name.startswith('yaml/') and name.endswith('.py') and entry.name not in {'cyaml.py', '_yaml.py'}:
            relative = name.removeprefix('yaml/')
        elif '.dist-info/' in name and entry.name == 'LICENSE':
            relative = 'LICENSE'
        else:
            continue
        data = Path(dist.locate_file(entry)).read_bytes()
        hashes.append(f'- `{name}`: `{hashlib.sha256(data).hexdigest()}`\n')
        if relative == '__init__.py':
            text = data.decode('utf-8')
            block = ('try:\n    from .cyaml import *\n    __with_libyaml__ = True\n'
                     'except ImportError:\n    __with_libyaml__ = False')
            if text.count(block) != 1:
                raise SystemExit('Upstream C-extension import changed; review the generator')
            text = text.replace(block, '__with_libyaml__ = False')
            data = ('# Generated by scripts/vendor_pyyaml.py; never edit by hand.\n' + text).encode('utf-8')
        elif relative.endswith('.py'):
            # Current upstream uses relative imports; keep a future absolute import private too.
            data = re.sub(rb'(?m)^(\s*(?:from|import)\s+)yaml\b', rb'\1pdfmd_yaml', data)
        files[relative] = data
    if '__init__.py' not in files or 'LICENSE' not in files:
        raise SystemExit('Installed PyYAML is missing its Python modules or MIT licence')
    files['VENDORED.md'] = (
        f'# Vendored PyYAML\n\nGenerated from installed PyYAML {version} (MIT licence, see LICENSE).\n'
        'Regenerate with `python3 scripts/vendor_pyyaml.py`; never edit by hand.\n'
        '`--version X.Y.Z` selects an installed release; `--check` reports drift.\n\n'
        'The package is renamed to `pdfmd_yaml`, so it never shadows `yaml`. Only\n'
        'Python modules are copied; cyaml, _yaml and compiled extensions are omitted.\n'
        'The C-extension import is removed and __with_libyaml__ is always False.\n\n'
        'Source files (SHA-256 before transformation):\n\n' + ''.join(hashes)
    ).encode('utf-8')
    return files


def current_tree() -> dict[str, bytes]:
    return {path.relative_to(TARGET).as_posix(): path.read_bytes()
            for path in sorted(TARGET.rglob('*')) if path.is_file() and '__pycache__' not in path.parts}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--version', default=PYYAML_VERSION, help='installed PyYAML version to copy')
    parser.add_argument('--check', action='store_true', help='report drift without writing')
    args = parser.parse_args()
    expected = build(args.version)
    if args.check:
        actual = current_tree()
        problems = [f'missing {name}' for name in expected if name not in actual]
        problems += [f'unexpected {name}' for name in actual if name not in expected]
        problems += [f'modified {name}' for name in expected if name in actual and actual[name] != expected[name]]
        if problems:
            print('\n'.join(problems), file=sys.stderr)
            return 1
        print(f'pdfmd_yaml matches installed PyYAML {args.version}')
        return 0
    if TARGET.exists():
        shutil.rmtree(TARGET)
    TARGET.mkdir(parents=True)
    for name, data in expected.items():
        path = TARGET / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f'Generated pdfmd_yaml from PyYAML {args.version}: {len(expected)} files')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
